macro_rules! declare_text_keys {
    ($($key:ident),+ $(,)?) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum TextKey {
            $($key),+
        }

        impl TextKey {
            pub const ALL: &'static [Self] = &[$(Self::$key),+];
        }
    };
}

